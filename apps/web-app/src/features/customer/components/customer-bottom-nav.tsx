import { NavLink, useLocation } from "react-router-dom";

const TABS = [
  { to: "/customer", label: "Home", end: true, icon: HomeIcon },
  { to: "/customer/browse", label: "Categories", icon: GridIcon },
  { to: "/customer/celebrities", label: "Celebrities", icon: StarIcon },
  { to: "/customer/orders", label: "Orders", icon: ReceiptIcon },
  { to: "/account", label: "Account", icon: UserIcon },
];

export function CustomerBottomNav() {
  const { pathname } = useLocation();
  const hidden =
    pathname.startsWith("/customer/checkout") ||
    pathname.startsWith("/customer/categories/") ||
    pathname.startsWith("/customer/products/") ||
    pathname.startsWith("/account/settings") ||
    pathname.startsWith("/customer/support") ||
    pathname.startsWith("/customer/legal/");

  if (hidden) {
    return null;
  }

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-50 border-t border-gray-200 bg-white">
      <div className="mx-auto flex max-w-lg items-center justify-around px-2 py-2">
        {TABS.map((tab) => (
          <NavLink
            key={tab.to}
            to={tab.to}
            end={tab.end}
            className={({ isActive }) => {
              const active =
                isActive ||
                (tab.to === "/customer/celebrities" &&
                  pathname.startsWith("/customer/celebrities"));

              return `flex flex-col items-center gap-0.5 px-2 py-1 text-[10px] font-semibold ${
                active ? "text-brand-primary" : "text-gray-500"
              }`;
            }}
          >
            <tab.icon className="h-5 w-5" />
            {tab.label}
          </NavLink>
        ))}
      </div>
    </nav>
  );
}

